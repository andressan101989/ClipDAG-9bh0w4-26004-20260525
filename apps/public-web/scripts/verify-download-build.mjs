import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = new URL('../dist/', import.meta.url);
const readPage = (path) => readFileSync(new URL(path, dist), 'utf8');
const routes = ['index', 'features', 'business', 'ads', 'marketplace', 'creators', 'live', 'whats-new', 'download', 'support', 'contact', 'privacy', 'terms'];
const publicPaths = new Set(['/', '/features', '/business', '/ads', '/marketplace', '/creators', '/live', '/whats-new', '/download', '/support', '/contact', '/privacy', '/terms']);
const privatePaths = new Set(['/business/home', '/business/login', '/business/ads']);

for (const route of routes) {
  const html = readPage(`${route}.html`);
  const robots = route === 'privacy' || route === 'terms' ? 'noindex,nofollow' : 'index,follow';
  assert.match(html, new RegExp(`name="robots" content="${robots}"`));
  assert.equal((html.match(/<h1\b/g) ?? []).length, 1, `${route}: H1`);
  assert.match(html, /<main\b/);
  assert.match(html, /<nav\b/);
  assert.match(html, /<footer\b/);
  assert.match(html, /href="\/business\/home"/, `${route}: Business handoff`);
  for (const [, href] of html.matchAll(/<a\b[^>]*\bhref="([^"]+)"/g)) {
    if (href.startsWith('#')) {
      assert.ok(html.includes(`id="${href.slice(1)}"`), `${route}: broken fragment ${href}`);
      continue;
    }
    const url = new URL(href, 'https://nelyon.app');
    assert.equal(url.origin, 'https://nelyon.app', `${route}: external link ${href}`);
    assert.ok(publicPaths.has(url.pathname) || privatePaths.has(url.pathname) || /^\/whats-new\/[a-z0-9-]+$/.test(url.pathname), `${route}: stale link ${href}`);
  }
}

const download = readPage('download.html');
assert.match(download, /<title>Download Nelyon<\/title>/);
assert.match(download, /href="https:\/\/nelyon\.app\/download"/);
assert.match(download, /Store links will be available here/);
assert.doesNotMatch(download, /href="https:\/\/(?:apps\.apple\.com|play\.google\.com)/);
assert.match(readPage('business.html'), /Build your business inside the ecosystem/);
assert.match(readPage('ads.html'), /Meet people in the moments that matter/);
assert.ok(!existsSync(new URL('business/home.html', dist)), 'private Business must not be generated by Astro');
const assets = join(fileURLToPath(dist), '_astro');
const output = readdirSync(assets).filter((name) => /\.js$/.test(name)).map((name) => readFileSync(join(assets, name), 'utf8')).join('\n');
assert.doesNotMatch(output, /BusinessAuthProvider|@supabase\/supabase-js|businessPayoutsApi|sellerCenterApi|hls\.js/);
console.log('Download, CTA matrix, public/private boundary and bundle isolation: PASS');
